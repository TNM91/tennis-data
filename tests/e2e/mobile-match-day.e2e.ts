test('keeps unsent scores on app return and protects Back, Reload and account changes', async ({page}, info) => {
  await page.setViewportSize({width: 320, height: 844})
  const {league, match, score} = await openMatch(page, true)
  await match.getByRole('button', {name: 'Enter scores', exact: true}).click()
  const sets = score.getByLabel('Set scores')
  await sets.fill('6-4, 6-3')
  await backgroundAndReturn(page)
  await page.evaluate(() => (window as unknown as MatchDayWindow).refreshNavigationSession())
  await expect(sets).toHaveValue('6-4, 6-3')
  expect(await score.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await score.getByRole('button', {name: 'Back to match', exact: true}).click()
  const prompt = page.getByRole('dialog', {name: 'Keep unsent scores', exact: true})
  await expect(prompt.getByRole('button', {name: 'Keep editing', exact: true})).toBeFocused()
  expect(await prompt.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.screenshot({path: info.outputPath('unsent-scores-large-text.png')})
  await page.keyboard.press('Escape')
  await expect(prompt).toHaveCount(0)
  await expect(sets).toHaveValue('6-4, 6-3')
  await score.getByRole('button', {name: 'Reload', exact: true}).click()
  await prompt.getByRole('button', {name: 'Keep editing', exact: true}).click()
  await expect(sets).toHaveValue('6-4, 6-3')
  await score.getByRole('button', {name: 'Reload', exact: true}).click()
  await prompt.getByRole('button', {name: 'Discard edits and continue', exact: true}).click()
  await expect(sets).toHaveValue('')
  await sets.fill('4-6, 3-6')
  await score.getByRole('button', {name: 'Back to match', exact: true}).click()
  await prompt.getByRole('button', {name: 'Discard edits and continue', exact: true}).click()
  await expect(match.getByRole('button', {name: 'Enter scores', exact: true})).toBeFocused()
  expect(await page.evaluate(() => (window as unknown as MatchDayWindow).scopedLeagueScore.scoreRequests)).toEqual([])
  await match.getByRole('button', {name: 'Enter scores', exact: true}).click()
  await expect(sets).toHaveValue('')
  await sets.fill('6-0, 6-0')
  await score.getByRole('button', {name: 'Back to match', exact: true}).click()
  await page.evaluate(() => (window as unknown as MatchDayWindow).switchNavigationOwner())
  await expect(prompt).toHaveCount(0)
  await expect(score).toHaveCount(0)
  await expect(league).toHaveCount(0)
})

test('recovers an uncertain submission once and keeps an unsent coordinator correction', async ({page}) => {
  const {league, match, score} = await openMatch(page)
  await page.evaluate(() => {(window as unknown as MatchDayWindow).scopedLeagueScore.lostScoreReply = true})
  await match.getByRole('button', {name: 'Enter scores', exact: true}).click()
  await score.getByLabel('Set scores').fill('6-4, 6-3')
  await score.getByRole('button', {name: 'Submit for review', exact: true}).click()
  await expect(score.getByRole('button', {name: 'Retry same change', exact: true})).toBeVisible()
  await score.getByRole('button', {name: 'Back to match', exact: true}).click()
  await expect(score.getByRole('status')).toHaveText('Retry the same change or reload the scorecard to check whether it saved.')
  await score.getByRole('button', {name: 'Retry same change', exact: true}).click()
  await expect(score.getByText('Awaiting coordinator review', {exact: true})).toBeVisible()
  await score.getByRole('button', {name: 'Return to match', exact: true}).click()
  await expect(match.getByRole('button', {name: 'View submitted score', exact: true})).toBeFocused()
  const requests = await page.evaluate(() => (window as unknown as MatchDayWindow).scopedLeagueScore.scoreRequests)
  expect(requests).toHaveLength(2)
  expect(requests[1]).toEqual(requests[0])
  await page.evaluate(() => {(window as unknown as MatchDayWindow).scopedLeagueScore.coordinator = true})
  await league.getByRole('button', {name: 'Refresh', exact: true}).click()
  await match.getByRole('button', {name: 'Review scorecard', exact: true}).click()
  await score.getByRole('button', {name: 'Request corrections', exact: true}).click()
  const note = score.getByLabel('What needs correcting?')
  await note.fill('Check which team won Singles 1.')
  await score.getByRole('button', {name: 'Back to match', exact: true}).click()
  await page.getByRole('dialog', {name: 'Keep unsent scores', exact: true}).getByRole('button', {name: 'Keep editing', exact: true}).click()
  await expect(note).toHaveValue('Check which team won Singles 1.')
  await backgroundAndReturn(page)
  await expect(note).toHaveValue('Check which team won Singles 1.')
  await score.getByRole('button', {name: 'Return scorecard', exact: true}).click()
  await expect(score.getByText('Corrections requested', {exact: true})).toBeVisible()
  await score.getByRole('button', {name: 'Return to match', exact: true}).click()
  await expect(match).toBeFocused()
  await expect(match.getByRole('button', {name: /^Remind captain/})).toBeVisible()
})

test('makes a private practice from an official result and closes nested work on account change', async ({page}, info) => {
  await page.setViewportSize({width: 320, height: 844})
  const {league, match} = await openMatch(page, true)
  const card: LeagueScoreCard = {revision: '33333333-3333-4333-8333-333333333333', state: 'approved', note: '',
    lines: [{format: 'singles', winner: 'A', score: '6-4, 6-3'}]}
  await page.evaluate(value => {(window as unknown as MatchDayWindow).scopedLeagueScore.card = value}, card)
  await league.getByRole('button', {name: 'Refresh', exact: true}).click()
  const openResult = match.getByRole('button', {name: 'View official result', exact: true})
  await openResult.click()
  const result = page.getByRole('dialog', {name: 'Official result', exact: true})
  const practice = result.getByRole('button', {name: 'Plan doubles practice', exact: true})
  await practice.click()
  const training = page.getByRole('dialog', {name: 'Level Up training', exact: true})
  await expect(training.getByRole('heading', {name: 'Next practice', exact: true})).toBeFocused()
  await expect(training).toContainText('Doubles match')
  expect(await training.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await training.getByRole('button', {name: 'Doubles first move', exact: true}).click()
  const target = 'Call our first move on 7 of 8 points.'
  await training.getByRole('textbox', {name: 'Practice target', exact: true}).fill(target)
  await training.getByRole('button', {name: 'Start training', exact: true}).click()
  await training.getByRole('combobox', {name: 'Self-rated proof (0–5)', exact: true}).selectOption('4')
  await training.getByRole('textbox', {name: 'How did you do against your target?', exact: true}).fill('Seven clear calls.')
  await training.getByRole('button', {name: 'Save completed session', exact: true}).click()
  await expect(training.getByRole('heading', {name: 'Training progress', exact: true})).toBeFocused()
  await expect(training.locator('.training-history-latest')).toContainText(target)
  await expect(training.locator('.training-history-latest')).not.toContainText('Shared with coach')
  await training.getByRole('button', {name: 'Close Level Up', exact: true}).click()
  await expect(practice).toBeFocused()
  await expect(result.getByText('6-4, 6-3', {exact: true})).toBeVisible()
  expect(await result.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.screenshot({path: info.outputPath('official-result-large-text.png')})
  expect(await page.evaluate(() => (window as unknown as MatchDayWindow).scopedLeagueScore.card)).toEqual(card)
  expect(await page.evaluate(() => (window as unknown as MatchDayWindow).scopedLeagueScore.scoreRequests)).toEqual([])
  await result.getByRole('button', {name: 'Plan singles practice', exact: true}).click()
  await expect(training).toContainText('Singles match')
  await expect(training.getByRole('button', {name: 'Doubles first move', exact: true})).toHaveCount(0)
  await training.getByRole('button', {name: 'Return depth', exact: true}).click()
  await training.getByRole('button', {name: 'Start training', exact: true}).click()
  await page.evaluate(() => (window as unknown as MatchDayWindow).refreshNavigationSession())
  await expect(training.getByRole('button', {name: 'Save completed session', exact: true})).toBeVisible()
  await page.evaluate(() => (window as unknown as MatchDayWindow).switchNavigationOwner())
  await expect(training).toHaveCount(0)
  await expect(result).toHaveCount(0)
  await expect(league).toHaveCount(0)
})
