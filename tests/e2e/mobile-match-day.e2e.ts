const origin = 'http://127.0.0.1:4285', matchId = '20000000-0000-4000-8000-000000000010'
let javascript = '', stylesheet = '', shell = ''
type MatchDayWindow = {
  scopedLeagueScore: {coordinator: boolean; card: LeagueScoreCard | null; lostScoreReply: boolean; scoreRequests: LeagueScoreChange[]}
  refreshNavigationSession: () => void
  switchNavigationOwner: () => void
}
async function openMatch(page: Page, large = false) {
  await page.clock.setFixedTime(new Date('2026-11-13T15:00:00Z'))
  await page.goto(origin + '/?league-score-review=match-day&training-inbox-review=1' + (large ? '&large=1' : ''))
  await page.getByRole('button', {name: 'Compete', exact: true}).click()
  await page.getByRole('button', {name: /^Browse leagues/}).click()
  const league = page.getByRole('dialog', {name: 'Competitions', exact: true})
  await league.getByRole('button', {name: /^Open league Northside Night League/}).click()
  await league.getByRole('button', {name: 'Schedule', exact: true}).click()
  return {
    league,
    match: league.locator('[data-competition-schedule-match="' + matchId + '"]'),
    score: page.locator('[aria-labelledby="league-scores-title"]'),
  }
}
async function backgroundAndReturn(page: Page) {
  await page.evaluate(() => {
    Object.defineProperty(document, 'visibilityState', {configurable: true, value: 'hidden'})
    document.dispatchEvent(new Event('visibilitychange'))
    Object.defineProperty(document, 'visibilityState', {configurable: true, value: 'visible'})
    document.dispatchEvent(new Event('visibilitychange'))
  })
}
